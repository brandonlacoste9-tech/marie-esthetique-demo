let lang = localStorage.getItem("marie-lang") || "fr";

function applyLang(l) {
  lang = l;
  localStorage.setItem("marie-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "ES" : "FR";
  document.title = l === "fr"
    ? "Marie Esthétique — Salon de beauté à Ottawa et Valence | Coiffure, maquillage, ongles"
    : "Marie Esthétique — Salón de belleza en Ottawa y Valencia | Peluquería, maquillaje, uñas";
}

document.getElementById("langToggle").addEventListener("click", () => {
  applyLang(lang === "fr" ? "es" : "fr");
});

